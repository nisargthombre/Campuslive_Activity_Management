/**
 * Retrieve club by ID with fallback
 */
export function getClubById(id) {
  if (!id) return initialFacultyClubsData[0]
  const found = initialFacultyClubsData.find(
    (c) => c.id.toLowerCase() === id.toLowerCase()
  )
  return found || initialFacultyClubsData[0]
}

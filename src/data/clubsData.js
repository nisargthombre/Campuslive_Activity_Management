/**
 * Retrieve club by its slug/ID.
 * Returns the matching club object or undefined if not found.
 */
export function getClubById(id) {
  if (!id) return undefined
  return initialClubsData.find(
    (club) => club.id.toLowerCase() === id.toLowerCase()
  )
}
